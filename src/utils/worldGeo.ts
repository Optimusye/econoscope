export function pointInPolygon(x: number, y: number, poly: LonLatPolygon): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    const intersect = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

const POLY_LIST = Object.values(CONTINENT_POLYGONS);

export function isLandCoordinate(lon: number, lat: number): boolean {
  return POLY_LIST.some((p) => pointInPolygon(lon, lat, p)) && !SEA_HOLES.some((h) => pointInPolygon(lon, lat, h));
}
