function buildImpact(
  conf: number,
  labels: [string, string, string, string, string, string]
): EconomicAlert["impactMatrix"] {
  return [
    [
      { label: labels[0], likelihood: Math.round(conf - 2) },
      { label: labels[1], likelihood: Math.round(conf - 6) },
    ],
    [
      { label: labels[2], likelihood: Math.round(conf - 14) },
      { label: labels[3], likelihood: Math.round(conf - 20) },
    ],
    [
      { label: labels[4], likelihood: Math.round(conf - 30) },
      { label: labels[5], likelihood: Math.round(conf - 38) },
    ],
  ];
}

function makeAlert(
  id: string,
  severity: EconomicAlert["severity"],
  regions: RegionKey[],
  category: EconomicAlert["category"],
  title: string,
  leadDays: number,
  confidence: number,
  sourceCounts: [number, number, number],
  why: string,
  causalChain: string[],
  impactLabels: [string, string, string, string, string, string],
  analog: EconomicAlert["analog"],
  topic: string,
  citationSources: SignalSource[],
  actions: string[],
  isShock = false
): EconomicAlert {
  return {
    id,
    severity,
    regions,
    category,
    title,
    leadDays,
    confidence,
    sourceCounts,
    why,
    causalChain,
    impactMatrix: buildImpact(confidence, impactLabels),
    analog,
    citations: citationSources.map((src) => [src, `${topic}: ${SOURCE_SUFFIX[src]}`]),
    actions,
    isShock,
  };
}

