const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function hashString(str: string): number {
  let h = 7;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) >>> 0;
  }
  return h;
}

function seededRandom(seed: number): () => number {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return s / 2147483647;
  };
}

export function getLabelsForTimeframe(tf: TimeframeKey): string[] {
  const { n, stepHours } = TIMEFRAMES[tf];
  const now = Date.now();
  return Array.from({ length: n }, (_, i) => {
    const d = new Date(now - (n - 1 - i) * stepHours * 3600 * 1000);
    const hh = String(d.getUTCHours()).padStart(2, "0");
    if (stepHours < 24) {
      return tf === "24H" ? `${hh}:00` : `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()} ${hh}h`;
    }
    return `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}`;
  });
}

export function generateSeries(
  key: string,
  tf: TimeframeKey,
  start: number,
  end: number,
  vol: number,
  spike: number
): number[] {
  const n = TIMEFRAMES[tf].n;
  const r = seededRandom(hashString(key + tf));
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = i / Math.max(1, n - 1);
    out.push(start + (end - start) * Math.pow(t, 1.7) + (r() - 0.5) * vol);
  }
  if (spike > 0) {
    const m = Math.ceil(n * 0.18);
    for (let i = n - m; i < n; i++) {
      out[i] += (spike * (i - (n - m) + 1)) / m;
    }
  }
  return out.map((v) => Number(v.toFixed(2)));
}

export function generateOfficialStepSeries(tf: TimeframeKey, start: number, end: number): number[] {
  const n = TIMEFRAMES[tf].n;
  const bucket = Math.ceil(n / 5);
  return Array.from({ length: n }, (_, i) => {
    const step = Math.min(4, Math.floor(i / bucket)) / 4;
    return Number((start + (end - start) * step).toFixed(2));
  });
}
